// --- Language Toggle Logic ---
let currentLang = localStorage.getItem('escalate_lang') || 'en';

function applyLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            // Check if it's an input/textarea placeholder or text content
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = translations[lang][key];
            } else {
                el.textContent = translations[lang][key];
            }
        }
    });

    // Update toggles UI
    document.querySelectorAll('.lang-toggle').forEach(toggle => {
        toggle.querySelector('.lang-en').classList.toggle('active', lang === 'en');
        toggle.querySelector('.lang-es').classList.toggle('active', lang === 'es');
    });

    // Save preference
    localStorage.setItem('escalate_lang', lang);
    currentLang = lang;
}

// Initial application
applyLanguage(currentLang);

// Toggle click events
document.querySelectorAll('.lang-toggle').forEach(toggle => {
    toggle.addEventListener('click', () => {
        const newLang = currentLang === 'en' ? 'es' : 'en';
        // Add a small fade effect on body
        document.body.style.opacity = '0.7';
        setTimeout(() => {
            applyLanguage(newLang);
            document.body.style.opacity = '1';
        }, 150);
    });
});


// --- Mobile Menu Toggle ---
const mobileBtn = document.getElementById('mobile-menu-btn');
const navMenu = document.getElementById('nav-menu');
const navLinks = document.querySelectorAll('.nav-link');

mobileBtn.addEventListener('click', () => {
    navMenu.classList.toggle('active');
    const icon = mobileBtn.querySelector('i');
    if (navMenu.classList.contains('active')) {
        icon.classList.remove('fa-bars');
        icon.classList.add('fa-times');
    } else {
        icon.classList.remove('fa-times');
        icon.classList.add('fa-bars');
    }
});

navLinks.forEach(link => {
    link.addEventListener('click', () => {
        navMenu.classList.remove('active');
        mobileBtn.querySelector('i').classList.remove('fa-times');
        mobileBtn.querySelector('i').classList.add('fa-bars');
    });
});

// --- Scroll Reveal Animation ---
const revealElements = document.querySelectorAll('section');
// Add reveal class to all sections initially
revealElements.forEach(el => {
    el.classList.add('reveal');
});

function checkReveal() {
    const windowHeight = window.innerHeight;
    const revealPoint = 150;

    revealElements.forEach(el => {
        const revealTop = el.getBoundingClientRect().top;
        if (revealTop < windowHeight - revealPoint) {
            el.classList.add('active');
        }
    });
}

// Check on load and scroll
window.addEventListener('load', checkReveal);
window.addEventListener('scroll', checkReveal);

// --- Form Submission Logic (Web3Forms AJAX) ---
document.getElementById('contactForm').addEventListener('submit', function(e) {
    e.preventDefault();
    const form = e.target;
    const btn = form.querySelector('button[type="submit"]');
    const originalText = btn.textContent;
    
    // Change button text while sending
    btn.textContent = currentLang === 'en' ? 'Sending...' : 'Enviando...';
    
    const formData = new FormData(form);

    fetch('https://api.web3forms.com/submit', {
        method: 'POST',
        body: formData
    })
    .then(async (response) => {
        let json = await response.json();
        if (response.status == 200) {
            btn.textContent = currentLang === 'en' ? 'Sent Successfully!' : '¡Enviado con éxito!';
            btn.style.background = 'var(--accent-cyan)';
            btn.style.color = 'var(--bg-black)';
            form.reset();
        } else {
            console.error(response);
            btn.textContent = currentLang === 'en' ? 'Error sending' : 'Error al enviar';
            btn.style.background = 'var(--highlight-red)';
        }
    })
    .catch(error => {
        console.error(error);
        btn.textContent = currentLang === 'en' ? 'Error sending' : 'Error al enviar';
        btn.style.background = 'var(--highlight-red)';
    })
    .finally(() => {
        setTimeout(() => {
            btn.textContent = originalText;
            btn.style.background = '';
            btn.style.color = '';
        }, 4000);
    });
});
